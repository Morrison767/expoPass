/* ─────────────── E-mail ─────────────── */

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[a-zA-Zа-яА-Я]{2,}$/

export function isValidEmail(value: string) {
  return EMAIL_RE.test(value.trim())
}

/* ─────────────── Телефон ─────────────── */

/**
 * Маска ввода с кодом страны.
 *
 * Казахстан и Россия (+7) получают привычный формат +7 (7XX) XXX-XX-XX;
 * ведущая «8» нормализуется в «7». Иные коды стран группируются по разрядам,
 * чтобы форма оставалась пригодной для нерезидентов.
 */
export function formatPhoneInput(raw: string): string {
  const digits = raw.replace(/\D/g, '')
  if (!digits) return ''

  let d = digits
  if (d[0] === '8') d = `7${d.slice(1)}`

  if (d[0] === '7') {
    const p = d.slice(0, 11)
    let out = '+7'
    if (p.length > 1) out += ` (${p.slice(1, 4)}`
    if (p.length >= 4) out += ')'
    if (p.length > 4) out += ` ${p.slice(4, 7)}`
    if (p.length > 7) out += `-${p.slice(7, 9)}`
    if (p.length > 9) out += `-${p.slice(9, 11)}`
    return out
  }

  // Иной код страны: +CC XXX XXX XXXX
  const p = d.slice(0, 15)
  const groups = [p.slice(0, 3), p.slice(3, 6), p.slice(6, 9), p.slice(9)].filter(Boolean)
  return `+${groups.join(' ')}`
}

export function phoneDigits(value: string) {
  return value.replace(/\D/g, '')
}

/** Международный минимум — 10 цифр, максимум по E.164 — 15 */
export function isValidPhone(value: string) {
  const length = phoneDigits(value).length
  return length >= 10 && length <= 15
}

/* ─────────────── Пароль ─────────────── */

export interface PasswordCheck {
  minLength: boolean
  hasLetter: boolean
  hasDigit: boolean
}

export function checkPassword(value: string): PasswordCheck {
  return {
    minLength: value.length >= 8,
    hasLetter: /[a-zA-Zа-яА-Я]/.test(value),
    hasDigit: /\d/.test(value),
  }
}

export function isValidPassword(value: string) {
  const check = checkPassword(value)
  return check.minLength && check.hasLetter && check.hasDigit
}

/* ─────────────── Ф.И.О. ─────────────── */

/** Допускаются буквы, дефис и апостроф: Yilmaz, Оспан-Кызы, O'Brien */
export function isValidName(value: string) {
  const trimmed = value.trim()
  return trimmed.length >= 2 && /^[\p{L}\s'-]+$/u.test(trimmed)
}

